// Builds web/scriptable.js — the full app as one file for the Scriptable iOS app.
// Usage: node web/build-scriptable.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('.', import.meta.url).pathname;
const r = f => readFileSync(dir + f, 'utf8');

const engine = r('engine.js');
const names = [...engine.matchAll(/^export\s+(?:async\s+)?(?:function|const|let)\s+([A-Za-z_$][\w$]*)/gm)].map(m => m[1]);
const engineBody = engine.replace(/^export\s+/gm, '');
const wrapped = `const E = (function () {\n${engineBody}\nreturn { ${names.join(', ')} };\n})();`;
const app = r('app.js').replace(/^import \* as E from '\.\/engine\.js';\s*$/m, '');
if (app.includes("from './engine.js'")) throw new Error('import not stripped');
const html = r('index.html');
const body = html.slice(html.indexOf('<body>') + 6, html.indexOf('</body>')).replace(/<script[\s\S]*?<\/script>/g, '');
const host = r('scriptable/host.js');

const build = new Date().toISOString().slice(0, 16).replace('T', ' ');
const out = `// M9ROFI_APP — مصروفي for Scriptable. Generated by web/build-scriptable.mjs on ${new Date().toISOString()}. Do not edit by hand.
const APP_BUILD = "${build}";
const ENGINE_WRAPPED = ${JSON.stringify(wrapped)};
const APP_SRC = ${JSON.stringify(app)};
const CSS_SRC = ${JSON.stringify(r('style.css'))};
const BODY_SRC = ${JSON.stringify(body)};
const E = new Function(ENGINE_WRAPPED + '\\nreturn E;')();
${host}
`;
writeFileSync(dir + 'scriptable.js', out);
console.log('scriptable.js', out.length, 'bytes,', names.length, 'engine exports');
